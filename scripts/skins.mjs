// Writes the light skins' part of gnome-extension/stylesheet.css (after the line "Skins, generated"): the
// stylesheet is written white on black, and each rule with a colour gets a twin for each light skin, under
// `#isleIsland.isle-skin-<name>`, its colours mapped by skinRules.js (as Daozai recolours what it has drawn).
// `node scripts/skins.mjs` rewrites it; `node scripts/skins.mjs --check` fails if it is not up to date
// (tests/extension/skins.test.js runs that).

import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

import {isLight, mapColor, PALETTES} from '../gnome-extension/src/skinRules.js';

const FILE = fileURLToPath(new URL('../gnome-extension/stylesheet.css', import.meta.url));
const MARK = '/* Skins, generated by scripts/skins.mjs from the rules above: do not edit below this line. */';
/** The skins with a paper of their own: the others keep the stylesheet's colours. */
const SKINS = Object.keys(PALETTES).filter(name => isLight(PALETTES[name]));
/** The actors the rules hang under, each given the skin's class by the controller. */
const ROOTS = ['#isleIsland', '#isleBubbles'];
/** Rules for other looks (glass and its tints, the system's accent) and for the top bar: not the skins'. */
const NOT_OURS = /isle-translucent|isle-glass-|isle-accent-system|#panel|isle-skin-|\.isle-(glass|compact|notch|pill)-bar/;
const COLOR = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g;

function parse(token) {
    if (token.startsWith('#')) {
        let hex = token.slice(1);
        if (hex.length <= 4)
            hex = [...hex].map(c => c + c).join('');
        const n = i => parseInt(hex.slice(i, i + 2), 16);
        return [n(0), n(2), n(4), hex.length === 8 ? n(6) : 255];
    }
    const parts = token.slice(token.indexOf('(') + 1, -1).split(',').map(part => parseFloat(part));
    return [parts[0], parts[1], parts[2], parts.length > 3 ? Math.round(parts[3] * 255) : 255];
}

function write([r, g, b, a]) {
    if (a >= 255)
        return `#${[r, g, b].map(v => v.toString(16).padStart(2, '0')).join('')}`;
    return `rgba(${r}, ${g}, ${b}, ${+(a / 255).toFixed(3)})`;
}

// A solid block of a colour (a button, a switch, a dot): white on it stays white.
function isColouredFill([r, g, b, a]) {
    const max = Math.max(r, g, b) / 255, min = Math.min(r, g, b) / 255;
    return a >= 180 && max - min > 0.3 && max > 0.45;
}

const isBlack = ([r, g, b]) => r + g + b < 30;
const isWhitish = ([r, g, b]) => Math.min(r, g, b) > 200 && Math.max(r, g, b) - Math.min(r, g, b) < 30;

/** A rule's declarations as the skin has them: only those whose colours change. */
function mapped(body, palette) {
    const declarations = body.split(';').map(part => part.trim()).filter(Boolean).map(part => {
        const at = part.indexOf(':');
        return [part.slice(0, at).trim(), part.slice(at + 1).trim()];
    });
    const fill = declarations.find(([name]) => name === 'background-color' || name === 'background');
    const onColour = Boolean(fill && [...fill[1].matchAll(COLOR)].some(([token]) => isColouredFill(parse(token))));
    const out = [];
    for (const [name, value] of declarations) {
        if (!COLOR.test(value))
            continue;
        COLOR.lastIndex = 0;
        const shadow = name.endsWith('shadow');
        const next = value.replace(COLOR, token => {
            const color = parse(token);
            // A shadow stays a shadow; white on a coloured block stays white.
            if (shadow && isBlack(color))
                return token;
            if (onColour && name === 'color' && isWhitish(color))
                return token;
            return write(mapColor(color, palette));
        });
        if (next !== value)
            out.push(`${name}: ${next};`);
    }
    return out;
}

function generate(base) {
    const rules = [...base.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/([^{}]+)\{([^{}]*)\}/g)]
        .map(([, selectors, body]) => [selectors.trim().split(/\s*,\s*/), body]);
    const lines = [MARK];
    for (const skin of SKINS) {
        const palette = PALETTES[skin];
        lines.push('', `/* ${skin} */`);
        for (const [selectors, body] of rules) {
            const ours = selectors.filter(selector => !NOT_OURS.test(selector));
            if (!ours.length)
                continue;
            const declarations = mapped(body, palette);
            if (!declarations.length)
                continue;
            const scoped = ours.flatMap(selector => {
                const root = ROOTS.find(name => selector === name || selector.startsWith(`${name} `) ||
                    selector.startsWith(`${name}.`) || selector.startsWith(`${name}:`));
                if (root)
                    return [`${root}.isle-skin-${skin}${selector.slice(root.length)}`];
                // Not under a root by its own words: under either.
                return ROOTS.map(name => `${name}.isle-skin-${skin} ${selector}`);
            });
            lines.push(`${scoped.join(', ')} { ${declarations.join(' ')} }`);
        }
    }
    return `${lines.join('\n')}\n`;
}

const text = readFileSync(FILE, 'utf8');
const at = text.indexOf(MARK);
const base = at < 0 ? `${text.trimEnd()}\n\n` : text.slice(0, at);
const next = base + generate(base);
if (process.argv.includes('--check')) {
    if (next !== text) {
        console.error('gnome-extension/stylesheet.css: the skins are not up to date; run node scripts/skins.mjs');
        process.exit(1);
    }
} else {
    writeFileSync(FILE, next);
    console.log(`${SKINS.join(', ')}: ${next.length - base.length} bytes`);
}
